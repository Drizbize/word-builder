#pragma once

#include "Vector2.hpp"
#include "raylib.h"
#include <raylib-cpp.hpp>
#include <vector>
#include <cmath>

class RectanglePro {
public:
    RRectangle rect;
    RVector2 origin = {0, 0};
    float rotation;

    RectanglePro(const RRectangle& rect, float rotation = 0.f)
        : rect(rect), rotation(rotation)
    {
    }

    std::vector<RVector2> getVertices() const {
        std::vector<RVector2> vertices(4);
        float rad = rotation * DEG2RAD;

        RVector2 corners[4] = {
            { -origin.x, -origin.y },                          // Top Left
            { rect.width - origin.x, -origin.y },              // Top Right
            { rect.width - origin.x, rect.height - origin.y }, // Bottom Right
            { -origin.x, rect.height - origin.y }              // Bottom Left
        };

        // Rotate corners and translate to world position
        for (int i = 0; i < 4; i++) {
            vertices[i] = corners[i].Rotate(rad) + rect.GetPosition();
        }
        return vertices;
    }

    RVector2 getByRelatedPosition(const RVector2& localRelPos) const {
        float rad = rotation * DEG2RAD;

        RVector2 relativeToPivot = localRelPos - origin;
        RVector2 rotatedPos = relativeToPivot.Rotate(rad);

        return rect.GetPosition() + rotatedPos;
    }

    bool checkCollision(const RectanglePro& other) {
        auto verts1 = this->getVertices();
        auto verts2 = other.getVertices();

        // Check for overlap on axes generated by both shapes
        return (isAxisOverlapping(verts1, verts2) && isAxisOverlapping(verts2, verts1));
    }

    void draw(const Color& color)
    {
        DrawRectanglePro(rect, origin, rotation, color);
    }

private:
    bool isAxisOverlapping(const std::vector<RVector2>& poly1, const std::vector<RVector2>& poly2) {
        for (size_t i = 0; i < poly1.size(); i++) {
            RVector2 p1 = poly1[i];
            RVector2 p2 = poly1[(i + 1) % poly1.size()];

            RVector2 edge = p1 - p2;
            RVector2 axis = { -edge.y, edge.x };
            
            float length = sqrt(axis.x * axis.x + axis.y * axis.y);
            if (length == 0) continue; // Safety check
            axis.x = axis.x / length;
            axis.y = axis.y / length;

            float min1, max1, min2, max2;
            projectPolygon(poly1, axis, min1, max1);
            projectPolygon(poly2, axis, min2, max2);

            if (max1 < min2 || max2 < min1)
                return false;
        }
        return true;
    }

    void projectPolygon(const std::vector<RVector2>& poly, RVector2 axis, float& min, float& max) {
        min = max = Vector2DotProduct((Vector2){poly[0].x, poly[0].y}, (Vector2){axis.x, axis.y});
        
        for (size_t i = 1; i < poly.size(); i++) {
            float projection = Vector2DotProduct((Vector2){poly[i].x, poly[i].y}, (Vector2){axis.x, axis.y});
            if (projection < min) min = projection;
            if (projection > max) max = projection;
        }
    }
};